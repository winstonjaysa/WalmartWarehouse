from playwright.sync_api import sync_playwright
import time
with sync_playwright() as p:
    b = p.chromium.launch(executable_path='/usr/bin/google-chrome', args=['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader'])
    pg = b.new_page(viewport={'width':1280,'height':800}); errs=[]
    pg.on('pageerror', lambda e: errs.append('pageerror '+str(e)))
    pg.on('console', lambda m: errs.append(m.text) if m.type=='error' else None)
    pg.goto('http://127.0.0.1:18431/parts/inky/camera_test.html')
    pg.wait_for_function('window.__ready', timeout=60000); time.sleep(1.5)
    D = lambda: pg.evaluate('cam.getDistance()')
    r = {}
    r['start'] = D()
    pg.click('button[aria-label="Zoom in"]'); time.sleep(1.2); r['afterPlus'] = D()
    pg.click('button[aria-label="Zoom out"]'); pg.click('button[aria-label="Zoom out"]'); time.sleep(1.2); r['afterMinus2'] = D()
    pg.focus('button[aria-label="Reset view"]'); pg.keyboard.press('Enter'); time.sleep(1.5); r['afterResetKbd'] = D()
    r['flyTo'] = pg.evaluate('Promise.race([cam.flyTo(racks[7]).then(v=>"resolved:"+v), new Promise(r=>setTimeout(()=>r("timeout"),5000))])'); r['afterFly'] = D()
    pg.evaluate('cam.goHome(0)'); time.sleep(0.3)
    for i in range(40): pg.mouse.move(640,400); pg.mouse.wheel(0,-400); time.sleep(0.03)
    time.sleep(1.5); r['minClamp'] = D()
    for i in range(60): pg.mouse.wheel(0,400); time.sleep(0.03)
    time.sleep(1.5); r['maxClamp'] = D()
    pg.evaluate('cam.zoomBy(1000)'); time.sleep(1.5); r['zoomBy1000'] = D()
    pg.evaluate('cam.zoomBy(0.0001)'); time.sleep(1.5); r['zoomBy0001'] = D()
    pg.evaluate('cam.goHome(0)'); time.sleep(0.3)
    pg.mouse.dblclick(640,400); time.sleep(1.5); r['afterDbl'] = D()
    pg.keyboard.press('Escape'); time.sleep(1.5); r['afterEsc'] = D()
    pg.click('#viewDock button[data-v="2d"]'); time.sleep(1.3); r['2d_camY_norm'] = pg.evaluate('(()=>{const o=camera.position.clone().sub(cam.controls.target).normalize();return o.y})()')
    pg.click('#viewDock button[data-v="3d"]'); time.sleep(1.3); r['3d_camY_norm'] = pg.evaluate('(()=>{const o=camera.position.clone().sub(cam.controls.target).normalize();return o.y})()')
    pg.evaluate('cam.goHome(0)'); time.sleep(0.2); pg.evaluate('cam.zoomBy(1.6)'); time.sleep(1.2)
    pg.screenshot(path='camera_test.png')
    r['disposeStyleGone'] = pg.evaluate('(()=>{cam.dispose();return !document.getElementById("gf-cam-style") && !document.querySelector(".gf-cam")})()')
    for k,v in r.items(): print(k, v)
    print('ERRS', errs)
    b.close()
